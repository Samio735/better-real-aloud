/**
 * Service worker — the only context allowed to talk to the Kokoro server.
 *
 * Why here and not in the content script:
 *   A content script shares the PAGE's origin for network purposes, so a
 *   fetch to http://127.0.0.1:8000 from a page is subject to that page's CORS
 *   rules and to Local Network Access restrictions. Host permissions do NOT
 *   lift CORS in a content script. In the extension context (this worker,
 *   with host_permissions declared) the request is exempt from CORS.
 *
 * Pipeline:
 *   content script: "speak sentence n"
 *     -> worker: POST /v1/audio/speech  (Kokoro/MLX)  -> WAV bytes -> data URL
 *     -> worker: hand data URL to the offscreen document to play
 *     -> offscreen: "ended"
 *     -> worker tells content script: advance to n+1
 *
 * MV3 lifecycle notes:
 *  - The worker is killed after ~30s idle. Audio playback is browser-process
 *    activity and is NOT activity for the worker, so we ping a chrome API on a
 *    timer while (and only while) something is playing.
 *  - Audio cannot be played from the worker; the offscreen document owns it.
 */

const MSG = {
  TOGGLE: 'ra-toggle',
  STOP: 'ra-stop',
  PING: 'ra-ping',
};

const DEFAULT_SETTINGS = {
  serverUrl: 'http://127.0.0.1:8000',
  model: 'mlx-community/Kokoro-82M-bf16',
  voice: 'af_heart',
  speed: 1.0,
  volume: 1.0,
  autoScroll: true,
  scrollMode: 'center',
  dimVisited: true,
  skipNav: true,
  prefetch: true,
  theme: 'auto',
};

const OFFSCREEN_PATH = 'offscreen.html';

// ---------------------------------------------------------------- keepalive

let keepAliveTimer = null;

function startKeepAlive() {
  if (keepAliveTimer) return;
  keepAliveTimer = setInterval(() => {
    chrome.runtime.getPlatformInfo(() => void chrome.runtime.lastError);
  }, 20000);
}

function stopKeepAlive() {
  if (keepAliveTimer) {
    clearInterval(keepAliveTimer);
    keepAliveTimer = null;
  }
}

// ------------------------------------------------------------- offscreen doc

let creatingOffscreen = null;

async function hasOffscreen() {
  if (chrome.runtime.getContexts) {
    const ctxs = await chrome.runtime.getContexts({
      contextTypes: ['OFFSCREEN_DOCUMENT'],
      documentUrls: [chrome.runtime.getURL(OFFSCREEN_PATH)],
    });
    return ctxs.length > 0;
  }
  return false;
}

async function ensureOffscreen() {
  if (await hasOffscreen()) return true;
  if (creatingOffscreen) {
    await creatingOffscreen;
    return true;
  }
  try {
    creatingOffscreen = chrome.offscreen.createDocument({
      url: OFFSCREEN_PATH,
      reasons: ['AUDIO_PLAYBACK'],
      justification: 'Play the speech audio generated by the local Kokoro server.',
    });
    await creatingOffscreen;
    creatingOffscreen = null;
    return true;
  } catch (e) {
    creatingOffscreen = null;
    // A concurrent create is harmless — the doc exists either way.
    if (String(e && e.message).includes('Only a single offscreen')) return true;
    console.warn('[Read Aloud] offscreen create failed:', e);
    return false;
  }
}

function toOffscreen(msg) {
  return new Promise((resolve) => {
    chrome.runtime.sendMessage({ ...msg, target: 'offscreen' }, (res) => {
      if (chrome.runtime.lastError) {
        resolve({ ok: false, error: chrome.runtime.lastError.message });
        return;
      }
      resolve(res || { ok: false, error: 'no response' });
    });
  });
}

// ------------------------------------------------------------------ settings

function getSettings() {
  return new Promise((resolve) => {
    chrome.storage.sync.get(DEFAULT_SETTINGS, (got) => {
      if (chrome.runtime.lastError) return resolve({ ...DEFAULT_SETTINGS });
      resolve({ ...DEFAULT_SETTINGS, ...(got || {}) });
    });
  });
}

// --------------------------------------------------------------- Kokoro TTS

/**
 * Synthesise one sentence. Returns a data URL the offscreen doc can play.
 *
 * response_format MUST be wav: the server's default is mp3, which requires
 * ffmpeg to be installed on the host. WAV is always available.
 */
async function synthesize(text, settings) {
  const base = (settings.serverUrl || DEFAULT_SETTINGS.serverUrl).replace(/\/+$/, '');
  const url = `${base}/v1/audio/speech`;

  const body = {
    model: settings.model || DEFAULT_SETTINGS.model,
    input: text,
    voice: settings.voice || DEFAULT_SETTINGS.voice,
    response_format: 'wav',
    speed: Number(settings.speed) || 1.0,
  };

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 60000);

  let res;
  try {
    res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
      signal: controller.signal,
    });
  } catch (e) {
    clearTimeout(timeout);
    const isAbort = e && e.name === 'AbortError';
    return {
      ok: false,
      error: isAbort
        ? 'Kokoro server timed out.'
        : 'Cannot reach the Kokoro server. Is it running?',
      offline: true,
    };
  }
  clearTimeout(timeout);

  if (!res.ok) {
    let detail = `HTTP ${res.status}`;
    try {
      const j = await res.json();
      if (j && j.detail) detail = typeof j.detail === 'string' ? j.detail : JSON.stringify(j.detail);
    } catch (e) {
      /* ignore */
    }
    return { ok: false, error: `Kokoro server error: ${detail}` };
  }

  const buf = await res.arrayBuffer();
  if (!buf || buf.byteLength === 0) {
    return {
      ok: false,
      error:
        'Kokoro returned no audio. If the server is using mp3 output, install ffmpeg or keep WAV.',
    };
  }

  return { ok: true, dataUrl: arrayBufferToDataUrl(buf, 'audio/wav'), bytes: buf.byteLength };
}

function arrayBufferToDataUrl(buf, mime) {
  const bytes = new Uint8Array(buf);
  // Chunked encode: String.fromCharCode.apply on a multi-MB array overflows
  // the argument limit and throws.
  let binary = '';
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    binary += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK));
  }
  return `data:${mime};base64,${btoa(binary)}`;
}

// ------------------------------------------------------------ health / voices

async function serverHealth(settings) {
  const base = (settings.serverUrl || DEFAULT_SETTINGS.serverUrl).replace(/\/+$/, '');
  try {
    const res = await fetch(`${base}/v1/models`, { method: 'GET' });
    return { ok: res.ok, status: res.status };
  } catch (e) {
    return { ok: false, error: String(e && e.message ? e.message : e) };
  }
}

async function fetchVoices(settings) {
  const base = (settings.serverUrl || DEFAULT_SETTINGS.serverUrl).replace(/\/+$/, '');
  const model = encodeURIComponent(settings.model || DEFAULT_SETTINGS.model);
  try {
    const res = await fetch(`${base}/v1/audio/voices?model=${model}`);
    if (!res.ok) return { ok: false, error: `HTTP ${res.status}` };
    const json = await res.json();
    const list = (json.data || json.voices || []).map((v) =>
      typeof v === 'string' ? v : v.id || v.name || v.voice
    );
    return { ok: true, voices: list.filter(Boolean) };
  } catch (e) {
    return { ok: false, error: 'Cannot reach the Kokoro server.' };
  }
}

// -------------------------------------------------------------- tab plumbing

async function ensureContentScript(tabId) {
  try {
    const res = await chrome.tabs.sendMessage(tabId, { type: MSG.PING });
    if (res && res.ok) return true;
  } catch (e) {
    /* not injected yet */
  }

  try {
    await chrome.scripting.insertCSS({ target: { tabId }, files: ['content.css'] });
  } catch (e) {
    /* already present */
  }

  try {
    await chrome.scripting.executeScript({ target: { tabId }, files: ['content.js'] });
  } catch (e) {
    console.warn('[Read Aloud] injection failed:', e.message);
    return false;
  }

  for (let i = 0; i < 12; i++) {
    try {
      const res = await chrome.tabs.sendMessage(tabId, { type: MSG.PING });
      if (res && res.ok) return true;
    } catch (e) {
      /* retry */
    }
    await new Promise((r) => setTimeout(r, 50));
  }
  return false;
}

async function activeTab() {
  const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  return tab || null;
}

function isRestricted(url) {
  if (!url) return true;
  return (
    url.startsWith('chrome://') ||
    url.startsWith('chrome-extension://') ||
    url.startsWith('edge://') ||
    url.startsWith('about:') ||
    url.startsWith('devtools://') ||
    url.startsWith('https://chrome.google.com/webstore') ||
    url.startsWith('https://chromewebstore.google.com')
  );
}

/**
 * The tab that owns the current playback session.
 *
 * Set from the sender of the most recent `ra-tts` message, NOT only from the
 * popup path: the content script also starts playback on its own (clicking a
 * sentence, the toolbar's play button, the keyboard shortcut), and in those
 * cases the popup never ran. Relying on the popup to set this left the tab id
 * null, so the "chunk finished" message had nowhere to go and reading stalled
 * after the first sentence with the highlight frozen.
 */
let sessionTabId = null;

async function tellTab(message, tabId) {
  const target = tabId != null ? tabId : sessionTabId;
  if (target == null) return { ok: false, error: 'no tab' };
  try {
    const res = await chrome.tabs.sendMessage(target, message);
    return res || { ok: true };
  } catch (e) {
    return { ok: false, error: e.message };
  }
}

// ------------------------------------------------------------- TTS streaming

/**
 * In-flight synthesis, keyed by tab+index, so audio for sentence n+1 can be
 * generated while sentence n is still playing. Kokoro takes ~0.6-3 s per
 * sentence, so without prefetch every sentence boundary would gap.
 *
 * IMPORTANT: the values are PROMISES of a synthesis result, not resolved
 * results. Consumers must await them before reading `.ok`.
 */
const prefetchCache = new Map();

/**
 * Which sentence index the offscreen document is currently playing.
 *
 * The completion event carries no payload of its own, so the worker has to
 * remember what it asked to play and tag the event with that index. Without the
 * tag the content script cannot tell which sentence finished, and a short
 * sentence that completes before the page starts waiting stalls the chain.
 */
let playingIndex = null;

async function playSentence({ tabId, index, text, settings }) {
  const key = `${tabId}:${index}`;

  // A cached entry is a pending promise — it MUST be awaited. Reading `.ok` off
  // the promise itself yielded undefined, so every prefetched sentence was
  // rejected as a failure and playback stopped dead after the first one.
  const cached = prefetchCache.get(key);
  prefetchCache.delete(key);

  let result;
  if (cached) {
    result = await cached;
  } else {
    result = await synthesize(text, settings);
  }

  if (!result || !result.ok) {
    return result || { ok: false, error: 'synthesis failed' };
  }

  const ok = await ensureOffscreen();
  if (!ok) {
    return { ok: false, error: 'Could not create the audio player document.' };
  }

  startKeepAlive();

  const playRes = await toOffscreen({
    type: 'ra-offscreen-play',
    dataUrl: result.dataUrl,
    volume: settings.volume,
    playbackRate: 1.0, // speed is applied server-side by Kokoro
  });

  if (!playRes.ok) {
    return { ok: false, error: playRes.error || 'audio playback failed' };
  }

  // Recorded only after playback has actually started, so a completion event
  // always has a valid index to report.
  playingIndex = index;

  // Kick off the NEXT sentence's synthesis now, while this one plays.
  maybePrefetch(tabId, index + 1, settings);

  return { ok: true };
}

function maybePrefetch(tabId, index, settings) {
  if (!settings.prefetch) return;
  const key = `${tabId}:${index}`;
  if (prefetchCache.has(key)) return;

  // The content script owns the sentence list; ask it for the text.
  chrome.tabs.sendMessage(tabId, { type: 'ra-get-sentence', index }, (res) => {
    if (chrome.runtime.lastError || !res || !res.ok || !res.text) return;
    const text = res.text;
    // Store the in-flight promise so a second request for the same sentence
    // does not duplicate work. Drop it again if it fails, so the real request
    // retries instead of reusing a failed result.
    const p = synthesize(text, settings).catch(() => null);
    prefetchCache.set(key, p);
    p.then((r) => {
      if (!r || !r.ok) prefetchCache.delete(key);
    });
    // Bound the cache; stale entries would hold audio in memory.
    if (prefetchCache.size > 6) {
      const oldest = prefetchCache.keys().next().value;
      if (oldest !== key) prefetchCache.delete(oldest);
    }
  });
}

function clearPrefetch() {
  prefetchCache.clear();
}

// ---------------------------------------------------------------- commands

async function startReading(tabId, opts = {}) {
  const settings = await getSettings();
  const ready = await ensureContentScript(tabId);
  if (!ready) {
    return { ok: false, error: 'Could not attach to this page.' };
  }
  sessionTabId = tabId;

  const health = await serverHealth(settings);
  if (!health.ok) {
    // Still attach the UI so the user sees a clear message, but say so.
    return {
      ok: false,
      error:
        'Kokoro server is not reachable. Start it with: ./run-server.sh',
      offline: true,
    };
  }

  return await tellTab({ type: 'ra-start', ...opts }, tabId);
}

// -------------------------------------------------------------- listeners

chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  (async () => {
    try {
      // ---- messages from the offscreen document
      if (msg && msg.type === 'ra-playback-ended') {
        // Tag the completion with the sentence it belongs to.
        await tellTab({ type: 'ra-chunk-ended', index: playingIndex });
        playingIndex = null;
        sendResponse({ ok: true });
        return;
      }

      if (msg && msg.type === 'ra-playback-error') {
        await tellTab({ type: 'ra-chunk-error', error: msg.error });
        sendResponse({ ok: true });
        return;
      }

      if (msg && msg.type === 'ra-offscreen-ready') {
        sendResponse({ ok: true });
        return;
      }

      // ---- messages from the content script
      if (msg && msg.type === 'ra-tts') {
        const settings = await getSettings();
        const tabId = sender.tab && sender.tab.id;
        if (tabId == null) {
          sendResponse({ ok: false, error: 'no tab context' });
          return;
        }
        // Remember which tab is speaking so the completion event below can be
        // routed back even when playback was started from the page itself.
        sessionTabId = tabId;
        const res = await playSentence({
          tabId,
          index: msg.index,
          text: msg.text,
          settings: { ...settings, ...(msg.settings || {}) },
        });
        sendResponse(res);
        return;
      }

      if (msg && msg.type === 'ra-stop-audio') {
        await toOffscreen({ type: 'ra-offscreen-stop' });
        clearPrefetch();
        playingIndex = null;
        stopKeepAlive();
        sendResponse({ ok: true });
        return;
      }

      if (msg && msg.type === 'ra-pause-audio') {
        const r = await toOffscreen({ type: 'ra-offscreen-pause' });
        sendResponse(r);
        return;
      }

      if (msg && msg.type === 'ra-resume-audio') {
        const r = await toOffscreen({ type: 'ra-offscreen-resume' });
        sendResponse(r);
        return;
      }

      if (msg && msg.type === 'ra-volume') {
        const r = await toOffscreen({ type: 'ra-offscreen-volume', volume: msg.volume });
        sendResponse(r);
        return;
      }

      // ---- messages from the popup
      if (msg && msg.type === 'ra-from-popup') {
        const tab = await activeTab();
        if (!tab) {
          sendResponse({ ok: false, error: 'No active tab.' });
          return;
        }
        if (isRestricted(tab.url)) {
          sendResponse({
            ok: false,
            error: 'This page cannot be read (browser-internal page).',
          });
          return;
        }

        switch (msg.command && msg.command.type) {
          case 'ra-start': {
            const res = await startReading(tab.id);
            sendResponse(res);
            return;
          }
          case MSG.TOGGLE: {
            const ready = await ensureContentScript(tab.id);
            if (!ready) {
              sendResponse({ ok: false, error: 'Could not attach to this page.' });
              return;
            }
            sessionTabId = tab.id;
            sendResponse(await tellTab({ type: MSG.TOGGLE }, tab.id));
            return;
          }
          case MSG.STOP:
            await toOffscreen({ type: 'ra-offscreen-stop' });
            clearPrefetch();
            playingIndex = null;
            stopKeepAlive();
            sendResponse(await tellTab({ type: MSG.STOP }, tab.id));
            return;
          default:
            sendResponse(await tellTab(msg.command, tab.id));
        }
        return;
      }

      if (msg && msg.type === 'ra-settings-changed') {
        const settings = await getSettings();
        const tabId = msg.tabId != null ? msg.tabId : sessionTabId;
        if (tabId != null) {
          await tellTab({ type: 'ra-settings', settings }, tabId);
        }
        sendResponse({ ok: true });
        return;
      }

      if (msg && msg.type === 'ra-check-server') {
        const settings = await getSettings();
        const health = await serverHealth(settings);
        if (!health.ok) {
          sendResponse({ ok: false, error: 'Server not reachable.' });
          return;
        }
        const voices = await fetchVoices(settings);
        sendResponse({ ok: true, voices: voices.ok ? voices.voices : [] });
        return;
      }

      if (msg && msg.type === 'ra-test-voice') {
        const settings = await getSettings();
        const text = msg.text || 'This is how I sound when reading a page.';
        const result = await synthesize(text, { ...settings, voice: msg.voice || settings.voice });
        if (!result.ok) {
          sendResponse(result);
          return;
        }
        const ok = await ensureOffscreen();
        if (!ok) {
          sendResponse({ ok: false, error: 'Could not create the audio player.' });
          return;
        }
        startKeepAlive();
        const playRes = await toOffscreen({
          type: 'ra-offscreen-play',
          dataUrl: result.dataUrl,
          volume: settings.volume,
          playbackRate: 1.0,
        });
        sendResponse(playRes);
        return;
      }

      sendResponse({ ok: false, error: 'unknown message' });
    } catch (e) {
      sendResponse({ ok: false, error: String(e && e.message ? e.message : e) });
    }
  })();
  return true;
});

chrome.commands.onCommand.addListener(async (command) => {
  const tab = await activeTab();
  if (!tab || isRestricted(tab.url)) return;

  if (command === 'toggle-read') {
    const ready = await ensureContentScript(tab.id);
    if (!ready) return;
    sessionTabId = tab.id;
    await tellTab({ type: MSG.TOGGLE }, tab.id);
  } else if (command === 'stop-read') {
    await toOffscreen({ type: 'ra-offscreen-stop' });
    clearPrefetch();
    playingIndex = null;
    stopKeepAlive();
    await tellTab({ type: MSG.STOP }, tab.id);
  } else if (command === 'rescan-read') {
    const ready = await ensureContentScript(tab.id);
    if (!ready) return;
    sessionTabId = tab.id;
    await tellTab({ type: 'ra-rescan' }, tab.id);
  } else if (command === 'section-next' || command === 'section-prev') {
    const ready = await ensureContentScript(tab.id);
    if (!ready) return;
    sessionTabId = tab.id;
    // The content script owns the block map, so it decides where a section
    // boundary is; the worker only forwards the direction.
    await tellTab(
      { type: 'ra-skip-section', dir: command === 'section-next' ? 1 : -1 },
      tab.id
    );
  }
});

chrome.tabs.onRemoved.addListener((tabId) => {
  if (tabId === sessionTabId) {
    sessionTabId = null;
    playingIndex = null;
    clearPrefetch();
    stopKeepAlive();
  }
});

// Fetching voices at install time gives the popup a warm cache.
chrome.runtime.onInstalled.addListener(async () => {
  const settings = await getSettings();
  await fetchVoices(settings);
});
